-- =============================================================
-- EMS MULTI-COMPANY HARDENING MIGRATION
-- Run once against the existing employee_management_system database
-- after taking a backup. This preserves existing IDs and data.
-- No team/team_members tables are created.
-- =============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(200) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.companies (company_id, company_name)
VALUES (1, 'StaffSync Demo Company')
ON CONFLICT (company_id) DO NOTHING;

-- Existing single-company installations are assigned to company 1.
UPDATE public.employees SET company_id = 1 WHERE company_id IS NULL;
UPDATE public.users SET company_id = 1 WHERE company_id IS NULL;
UPDATE public.department SET company_id = 1 WHERE company_id IS NULL;
UPDATE public.designation SET company_id = 1 WHERE company_id IS NULL;
UPDATE public.projects SET company_id = 1 WHERE company_id IS NULL;
UPDATE public.tasks SET company_id = 1 WHERE company_id IS NULL;

-- Preserve any other already-used company IDs before adding FKs.
INSERT INTO public.companies (company_id, company_name)
SELECT ids.company_id, 'Company ' || ids.company_id
FROM (
    SELECT company_id FROM public.employees
    UNION SELECT company_id FROM public.users
    UNION SELECT company_id FROM public.department
    UNION SELECT company_id FROM public.designation
    UNION SELECT company_id FROM public.projects
    UNION SELECT company_id FROM public.tasks
) ids
WHERE ids.company_id IS NOT NULL
ON CONFLICT (company_id) DO NOTHING;

-- Attendance, leave and payroll inherit their tenant from the employee.
ALTER TABLE public.attendance ADD COLUMN IF NOT EXISTS company_id BIGINT;
ALTER TABLE public.leaves ADD COLUMN IF NOT EXISTS company_id BIGINT;
ALTER TABLE public.payroll ADD COLUMN IF NOT EXISTS company_id BIGINT;

UPDATE public.attendance a
SET company_id = e.company_id
FROM public.employees e
WHERE e.employee_id = a.employee_id AND a.company_id IS NULL;

UPDATE public.leaves l
SET company_id = e.company_id
FROM public.employees e
WHERE e.employee_id = l.employee_id AND l.company_id IS NULL;

UPDATE public.payroll p
SET company_id = e.company_id
FROM public.employees e
WHERE e.employee_id = p.employee_id AND p.company_id IS NULL;

-- The relation table is tenant-owned too; enforce that employee and project
-- assignments cannot cross company boundaries.
ALTER TABLE public.employee_project ADD COLUMN IF NOT EXISTS company_id BIGINT;

-- Keep legacy/JPA join-table inserts compatible while enforcing same-company membership.
CREATE OR REPLACE FUNCTION public.set_employee_project_company_id()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $trigger$
DECLARE
    employee_company BIGINT;
    project_company BIGINT;
BEGIN
    SELECT e.company_id INTO employee_company
    FROM public.employees e
    WHERE e.employee_id = NEW.employee_id;

    SELECT p.company_id INTO project_company
    FROM public.projects p
    WHERE p.project_id = NEW.project_id;

    IF employee_company IS NULL OR project_company IS NULL
       OR employee_company <> project_company THEN
        RAISE EXCEPTION 'Employee and project must belong to the same company';
    END IF;

    NEW.company_id := project_company;
    RETURN NEW;
END;
$trigger$;

DROP TRIGGER IF EXISTS trg_employee_project_company_id ON public.employee_project;
CREATE TRIGGER trg_employee_project_company_id
BEFORE INSERT OR UPDATE OF employee_id, project_id, company_id
ON public.employee_project
FOR EACH ROW EXECUTE FUNCTION public.set_employee_project_company_id();

UPDATE public.employee_project ep
SET company_id = p.company_id
FROM public.projects p
WHERE p.project_id = ep.project_id AND ep.company_id IS NULL;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.employee_project ep
        JOIN public.employees e ON e.employee_id = ep.employee_id
        JOIN public.projects p ON p.project_id = ep.project_id
        WHERE e.company_id <> p.company_id
           OR ep.company_id IS NULL
    ) THEN
        RAISE EXCEPTION 'Cross-company or orphan employee_project rows exist; resolve them before rerunning this migration';
    END IF;

    IF EXISTS (SELECT 1 FROM public.attendance WHERE company_id IS NULL)
       OR EXISTS (SELECT 1 FROM public.leaves WHERE company_id IS NULL)
       OR EXISTS (SELECT 1 FROM public.payroll WHERE company_id IS NULL) THEN
        RAISE EXCEPTION 'Attendance, leave, or payroll rows have no matching company employee; resolve orphan rows before rerunning this migration';
    END IF;
END $$;

-- Register company IDs inherited from legacy employee-owned tables.
INSERT INTO public.companies (company_id, company_name)
SELECT DISTINCT company_id, 'Company ' || company_id
FROM (
    SELECT company_id FROM public.attendance
    UNION SELECT company_id FROM public.leaves
    UNION SELECT company_id FROM public.payroll
    UNION SELECT company_id FROM public.employee_project
) inherited
WHERE company_id IS NOT NULL
ON CONFLICT (company_id) DO NOTHING;

ALTER TABLE public.employees ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.users ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.department ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.designation ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.projects ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.tasks ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.attendance ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.leaves ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.payroll ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE public.employee_project ALTER COLUMN company_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_employees_company_employee
    ON public.employees (company_id, employee_id);
CREATE INDEX IF NOT EXISTS idx_users_company_username
    ON public.users (company_id, username);
CREATE INDEX IF NOT EXISTS idx_projects_company_project
    ON public.projects (company_id, project_id);
CREATE INDEX IF NOT EXISTS idx_tasks_company_task
    ON public.tasks (company_id, task_id);
CREATE INDEX IF NOT EXISTS idx_attendance_company_employee
    ON public.attendance (company_id, employee_id);
CREATE INDEX IF NOT EXISTS idx_leaves_company_employee
    ON public.leaves (company_id, employee_id);
CREATE INDEX IF NOT EXISTS idx_payroll_company_employee
    ON public.payroll (company_id, employee_id);
CREATE INDEX IF NOT EXISTS idx_employee_project_company_employee
    ON public.employee_project (company_id, employee_id);
CREATE INDEX IF NOT EXISTS idx_employee_project_company_project
    ON public.employee_project (company_id, project_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_employees_id_company
    ON public.employees (employee_id, company_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_projects_id_company
    ON public.projects (project_id, company_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employees_company') THEN
        ALTER TABLE public.employees ADD CONSTRAINT fk_employees_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_company') THEN
        ALTER TABLE public.users ADD CONSTRAINT fk_users_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_department_company') THEN
        ALTER TABLE public.department ADD CONSTRAINT fk_department_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_designation_company') THEN
        ALTER TABLE public.designation ADD CONSTRAINT fk_designation_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_projects_company') THEN
        ALTER TABLE public.projects ADD CONSTRAINT fk_projects_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_tasks_company') THEN
        ALTER TABLE public.tasks ADD CONSTRAINT fk_tasks_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_attendance_company') THEN
        ALTER TABLE public.attendance ADD CONSTRAINT fk_attendance_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_leaves_company') THEN
        ALTER TABLE public.leaves ADD CONSTRAINT fk_leaves_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_payroll_company') THEN
        ALTER TABLE public.payroll ADD CONSTRAINT fk_payroll_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employee_project_company') THEN
        ALTER TABLE public.employee_project ADD CONSTRAINT fk_employee_project_company
            FOREIGN KEY (company_id) REFERENCES public.companies(company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_attendance_employee_company') THEN
        ALTER TABLE public.attendance ADD CONSTRAINT fk_attendance_employee_company
            FOREIGN KEY (employee_id, company_id)
            REFERENCES public.employees(employee_id, company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_leaves_employee_company') THEN
        ALTER TABLE public.leaves ADD CONSTRAINT fk_leaves_employee_company
            FOREIGN KEY (employee_id, company_id)
            REFERENCES public.employees(employee_id, company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_payroll_employee_company') THEN
        ALTER TABLE public.payroll ADD CONSTRAINT fk_payroll_employee_company
            FOREIGN KEY (employee_id, company_id)
            REFERENCES public.employees(employee_id, company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employee_project_employee_company') THEN
        ALTER TABLE public.employee_project ADD CONSTRAINT fk_employee_project_employee_company
            FOREIGN KEY (employee_id, company_id)
            REFERENCES public.employees(employee_id, company_id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employee_project_project_company') THEN
        ALTER TABLE public.employee_project ADD CONSTRAINT fk_employee_project_project_company
            FOREIGN KEY (project_id, company_id)
            REFERENCES public.projects(project_id, company_id) ON DELETE RESTRICT;
    END IF;
END $;

-- Keep the identity sequence above all preserved company IDs.
SELECT setval(
    pg_get_serial_sequence('public.companies', 'company_id'),
    GREATEST((SELECT COALESCE(MAX(company_id), 1) FROM public.companies), 1),
    true
);

COMMIT;
