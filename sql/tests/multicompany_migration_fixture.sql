-- Minimal representative pre-migration EMS schema for CI migration validation.
-- This is a disposable test database fixture, not a production schema script.

CREATE TABLE public.department (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(150),
    location VARCHAR(150),
    description TEXT,
    company_id BIGINT
);

CREATE TABLE public.designation (
    designation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designation_title VARCHAR(150),
    min_salary NUMERIC,
    max_salary NUMERIC,
    company_id BIGINT
);

CREATE TABLE public.employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255),
    department_id INTEGER,
    designation_id INTEGER,
    manager_id INTEGER,
    hr_id INTEGER,
    company_id BIGINT
);

CREATE TABLE public.users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100),
    employee_id INTEGER,
    role_id INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    company_id BIGINT
);

CREATE TABLE public.projects (
    project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(200),
    start_date DATE,
    end_date DATE,
    manager_id INTEGER,
    company_id BIGINT
);

CREATE TABLE public.tasks (
    task_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name VARCHAR(200),
    description TEXT,
    priority VARCHAR(30),
    status VARCHAR(30),
    start_date DATE,
    due_date DATE,
    project_id INTEGER,
    assigned_to INTEGER,
    company_id BIGINT
);

CREATE TABLE public.attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    att_date DATE,
    status VARCHAR(30),
    check_in_time TIME,
    check_out_time TIME,
    employee_id INTEGER
);

CREATE TABLE public.leaves (
    leave_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_date DATE,
    to_date DATE,
    reason VARCHAR(500),
    status VARCHAR(30),
    employee_id INTEGER
);

CREATE TABLE public.payroll (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pay_month VARCHAR(20),
    basic_salary NUMERIC,
    allowances NUMERIC,
    deductions NUMERIC,
    net_salary NUMERIC,
    payment_date DATE,
    employee_id INTEGER
);

CREATE TABLE public.employee_project (
    employee_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    PRIMARY KEY (employee_id, project_id)
);

